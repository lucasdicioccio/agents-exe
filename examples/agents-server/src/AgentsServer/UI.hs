{-# LANGUAGE OverloadedStrings #-}

{- | A small chat page for local use, served at @\/@.

It is one self-contained HTML document: no build step, no assets, no
libraries. It talks to the same JSON API as any other client, so it is also
a worked example of that API — starting a session, following its event
stream, and completing deferred tool calls.

It is meant for a person at the machine running the server. 'uiEnabled'
keeps it to loopback binds unless the server also authenticates its callers.
-}
module AgentsServer.UI (
    uiPage,
    uiEnabled,
) where

import Data.Text (Text)
import qualified Data.Text as Text

{- | Whether to serve the page: on a loopback bind, or when callers are
authenticated. On a public bind without tokens the API refuses browser
requests anyway (the Origin check), so the page could only mislead.
-}
uiEnabled :: Text -> Bool -> Bool
uiEnabled bind authenticated =
    authenticated || bind `elem` ["127.0.0.1", "localhost", "::1", "[::1]"]

