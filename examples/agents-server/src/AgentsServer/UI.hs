-- | The page's behaviour. Kept apart so the markup above stays readable.
jsSource :: Text
jsSource =
    Text.unlines
        [ "const $ = s => document.querySelector(s);"
        , "let sid = null, es = null, streaming = null;"
        , "const token = () => sessionStorage.getItem('token') || '';"
        , "$('#token').value = token();"
        , "$('#token').oninput = e => sessionStorage.setItem('token', e.target.value);"
        , ""
        , "async function api(path, opts = {}) {"
        , "  const h = Object.assign({'Content-Type': 'application/json'}, opts.headers || {});"
        , "  if (token()) h['Authorization'] = 'Bearer ' + token();"
        , "  const r = await fetch(path, Object.assign({}, opts, {headers: h}));"
        , "  const body = r.status === 204 ? null : await r.json().catch(() => null);"
        , "  if (!r.ok) throw new Error(body && body.message ? body.message : r.status + ' ' + r.statusText);"
        , "  return body;"
        , "}"
        , ""
        , "function note(text, cls) {"
        , "  const d = document.createElement('div');"
        , "  d.className = 'msg ' + (cls || '');"
        , "  d.textContent = text;"
        , "  $('#log').appendChild(d);"
        , "  $('#log').scrollTop = $('#log').scrollHeight;"
        , "  return d;"
        , "}"
        , ""
        , "// The text a user turn carries; queryText is a bare string unless it has media."
        , "function userText(c) {"
        , "  const q = c && c.userQuery;"
        , "  if (!q) return null;"
        , "  return typeof q === 'string' ? q : q.queryText;"
        , "}"
        , ""
        , "function render(session, pending) {"
        , "  const log = $('#log');"
        , "  log.innerHTML = '';"
        , "  streaming = null;"
        , "  const turns = (session && session.turns ? session.turns : []).slice().reverse();"
        , "  for (const turn of turns) {"
        , "    const c = turn.contents || {};"
        , "    if (turn.tag === 'UserTurn' || turn.tag === 'PartialUserTurn') {"
        , "      const t = userText(c);"
        , "      if (t) note(t, 'user');"
        , "    } else if (turn.tag === 'LlmTurn') {"
        , "      const r = c.llmResponse || {};"
        , "      const d = document.createElement('div');"
        , "      d.className = 'msg';"
        , "      d.innerHTML = '<div class=\\'who\\'>agent</div>';"
        , "      d.appendChild(document.createTextNode(r.responseText || ''));"
        , "      const calls = c.llmToolCalls || [];"
        , "      if (calls.length) {"
        , "        const s = document.createElement('div');"
        , "        s.className = 'tools';"
        , "        s.textContent = 'called ' + calls.map(x => (x.function || {}).name).join(', ');"
        , "        d.appendChild(s);"
        , "      }"
        , "      log.appendChild(d);"
        , "    }"
        , "  }"
        , "  for (const call of pending || []) deferredCard(call);"
        , "  log.scrollTop = log.scrollHeight;"
        , "}"
        , ""
        , "// A deferred call is one this server will not run: a worker answers it."
        , "function deferredCard(call) {"
        , "  const box = document.createElement('div');"
        , "  box.className = 'card';"
        , "  const h = document.createElement('h3');"
        , "  h.textContent = 'waiting on ' + call.tool;"
        , "  const args = document.createElement('pre');"
        , "  args.textContent = ((call.call || {}).function || {}).arguments || '';"
        , "  const input = document.createElement('textarea');"
        , "  input.rows = 2;"
        , "  input.placeholder = 'The result of this call';"
        , "  const go = document.createElement('button');"
        , "  go.textContent = 'Send result';"
        , "  go.onclick = async () => {"
        , "    go.disabled = true;"
        , "    try {"
        , "      await api('/v1/continuations/' + call.continuation_token, {"
        , "        method: 'POST', body: JSON.stringify({result: input.value})"
        , "      });"
        , "      box.remove();"
        , "    } catch (e) { go.disabled = false; note('could not send: ' + e.message); }"
        , "  };"
        , "  box.append(h, args, input, go);"
        , "  $('#log').appendChild(box);"
        , "}"
        , ""
        , "async function refresh() {"
        , "  if (!sid) return;"
        , "  const s = await api('/v1/sessions/' + sid);"
        , "  $('#status').textContent = s.status;"
        , "  render(s.session, s.pending);"
        , "}"
        , ""
        , "function follow(id) {"
        , "  if (es) es.close();"
        , "  // EventSource cannot set headers, so a token travels as a query parameter,"
        , "  // which this server accepts on this endpoint only."
        , "  const q = token() ? '?access_token=' + encodeURIComponent(token()) : '';"
        , "  es = new EventSource('/v1/sessions/' + id + '/events' + q);"
        , "  es.addEventListener('text.delta', e => {"
        , "    const d = JSON.parse(e.data);"
        , "    if (!streaming) { streaming = note('', ''); }"
        , "    streaming.textContent += d.text;"
        , "    $('#log').scrollTop = $('#log').scrollHeight;"
        , "  });"
        , "  for (const kind of ['session.updated', 'run.stopped', 'calls.deferred', 'session.failed']) {"
        , "    es.addEventListener(kind, () => refresh().catch(() => {}));"
        , "  }"
        , "  es.addEventListener('snapshot', e => { $('#status').textContent = JSON.parse(e.data).status; });"
        , "}"
        , ""
        , "async function openSession(id, title) {"
        , "  sid = id;"
        , "  $('#title').textContent = title || id.slice(0, 8);"
        , "  for (const li of document.querySelectorAll('#sessions li')) li.classList.toggle('on', li.dataset.id === id);"
        , "  await refresh();"
        , "  follow(id);"
        , "}"
        , ""
        , "async function listSessions() {"
        , "  const r = await api('/v1/sessions?limit=50');"
        , "  const ul = $('#sessions');"
        , "  ul.innerHTML = '';"
        , "  for (const s of r.sessions) {"
        , "    const li = document.createElement('li');"
        , "    li.dataset.id = s.session_id;"
        , "    li.textContent = (s.agent || 'session') + ' · ' + s.status;"
        , "    li.classList.toggle('on', s.session_id === sid);"
        , "    li.onclick = () => openSession(s.session_id, s.agent);"
        , "    ul.appendChild(li);"
        , "  }"
        , "}"
        , ""
        , "async function send() {"
        , "  const text = $('#prompt').value.trim();"
        , "  if (!text) return;"
        , "  $('#prompt').value = '';"
        , "  note(text, 'user');"
        , "  try {"
        , "    if (sid) {"
        , "      await api('/v1/sessions/' + sid + '/messages', {method: 'POST', body: JSON.stringify({prompt: text})});"
        , "    } else {"
        , "      const s = await api('/v1/sessions', {"
        , "        method: 'POST',"
        , "        body: JSON.stringify({agent: $('#agent').value, prompt: text})"
        , "      });"
        , "      await openSession(s.session_id, s.agent);"
        , "      await listSessions();"
        , "    }"
        , "  } catch (e) { note('could not send: ' + e.message); }"
        , "}"
        , ""
        , "$('#send').onclick = send;"
        , "$('#prompt').onkeydown = e => {"
        , "  if (e.key === 'Enter' && !e.shiftKey) { e.preventDefault(); send(); }"
        , "};"
        , "$('#prompt').oninput = e => {"
        , "  e.target.style.height = 'auto';"
        , "  e.target.style.height = e.target.scrollHeight + 'px';"
        , "};"
        , "$('#new').onclick = () => {"
        , "  if (es) es.close();"
        , "  sid = null;"
        , "  $('#title').textContent = 'New chat';"
        , "  $('#status').textContent = '\\u2014';"
        , "  $('#log').innerHTML = '';"
        , "  listSessions().catch(() => {});"
        , "};"
        , ""
        , "(async function start() {"
        , "  try {"
        , "    const agents = await api('/v1/agents');"
        , "    for (const a of agents) {"
        , "      const o = document.createElement('option');"
        , "      o.value = a.slug;"
        , "      o.textContent = a.slug + (a.description ? ' - ' + a.description : '');"
        , "      $('#agent').appendChild(o);"
        , "    }"
        , "    if (!agents.length) note('This server has no agents.');"
        , "    await listSessions();"
        , "  } catch (e) {"
        , "    note('Could not reach the API: ' + e.message + (token() ? '' : ' — a bearer token may be required.'));"
        , "  }"
        , "})();"
        ]
